import Foundation
import PackagePlugin

/// Stamps the build it runs in: generates `BuildVersion.string`, the package version plus the commit
/// the tree was built from — `0.1.0+539cf51`, with `-dirty` when the tree had changes. Both
/// executables use it, so `tgkb --version`, `tgkb-mcp --version`, `serverInfo.version` and
/// `tgkb doctor` print one string (<doc:Design> § *Every build says which commit it is*).
///
/// A **prebuild** command, so it runs before every build and a new commit or an edit shows up on an
/// incremental one. It runs the system `git` — a prebuild command cannot use a tool built from
/// this package — inside SwiftPM's plugin sandbox, which allows reads anywhere, so a worktree whose
/// `.git` points outside the package works too. `GIT_OPTIONAL_LOCKS=0` keeps `git status` from
/// trying to refresh the index, a write the sandbox would refuse.
///
/// Each executable target runs it, within one build; a tree edited between the two runs could give
/// them different strings, which `Scripts/check-invariants.sh` reports.
@main
struct StampVersion: BuildToolPlugin {

    /// The package version. Everything after the `+` is build metadata, from git.
    static let packageVersion = "0.1.0"

    /// `$1` is the package directory, `$2` the output directory. Untracked files count as changes:
    /// SwiftPM compiles every source file under a target, tracked or not. Without git, or outside a
    /// repository, the commit is `unknown` rather than a guess. The file is rewritten only when
    /// the string changed, so an unchanged tree does not recompile the executables.
    static let script = """
        set -e
        mkdir -p "$2"
        commit=$(git -C "$1" rev-parse --short HEAD 2>/dev/null || echo unknown)
        changes=$(git -C "$1" status --porcelain 2>/dev/null | head -n 1)
        version="\(packageVersion)+${commit}${changes:+-dirty}"
        file="$2/BuildVersion.swift"
        source="// Generated by the StampVersion build plugin. Do not edit.
        enum BuildVersion { static let string = \\"$version\\" }"
        [ "$(cat "$file" 2>/dev/null)" = "$source" ] || printf '%s\\n' "$source" > "$file"
        """

    func createBuildCommands(context: PluginContext, target: Target) throws -> [Command] {
        let output = context.pluginWorkDirectoryURL.appending(path: "generated")
        return [.prebuildCommand(
            displayName: "Stamp the build version into \(target.name)",
            executable: URL(filePath: "/bin/sh"),
            arguments: ["-c", Self.script, "stamp", context.package.directoryURL.path, output.path],
            environment: ["GIT_OPTIONAL_LOCKS": "0"],
            outputFilesDirectory: output)]
    }
}
