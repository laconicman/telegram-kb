#!/bin/sh
# The version both binaries report, and the one rule for it (#12): the package version, then `+`
# and the short hash of the commit the tree was built from, with `-dirty` when the tree had changes —
# `0.1.0+539cf51`, `0.1.0+539cf51-dirty` — or `unknown` where no commit can be named honestly.
#
# One rule, used twice: the StampVersion plugin generates BuildVersion.swift from it, and
# check-invariants.sh checks the built binaries against it. Two copies of it drifted twice in one
# review (Devin Review, #19); `VersionTests` holds this one to its cases.
#
# - Git is believed only when its worktree root IS the package directory. An unpacked archive inside
#   some other checkout has no `.git` of its own, and `git -C` would walk up to that checkout and
#   name a commit this code was never part of. A linked worktree passes: its `.git` file leads
#   `--show-toplevel` back to the package. Paths are compared physically, so /tmp and /private/tmp
#   agree.
# - No commit — no git, another repository's tree, or a repository before its first commit — is
#   `unknown`, with no `-dirty`: there is nothing for the changes to be relative to.
# - A tracked file changed anywhere is a change. An untracked file is one only where SwiftPM would
#   compile it — under Sources/ or Plugins/ — since it compiles every file there, tracked or not.
#   Elsewhere (a tool's .claude/, scratch notes) it is not: the plugin's git does not read the
#   user's global ignore file, so counting untracked files everywhere made the stamp depend on whose
#   configuration built it.
#
# usage: build-version.sh <package-dir>                 prints the version
#        build-version.sh <package-dir> <output-dir>    writes <output-dir>/BuildVersion.swift, and
#                                                       only when its content changed, so an
#                                                       unchanged tree does not recompile
set -e
package_version=0.1.0

commit=unknown
changes=
top=$(git -C "$1" rev-parse --show-toplevel 2>/dev/null || true)
if [ -n "$top" ] && [ "$(cd "$top" && pwd -P)" = "$(cd "$1" && pwd -P)" ] \
   && hash=$(git -C "$1" rev-parse --short HEAD 2>/dev/null); then
  commit=$hash
  changes=$(git -C "$1" status --porcelain --untracked-files=no 2>/dev/null | head -n 1)
  [ -n "$changes" ] \
    || changes=$(git -C "$1" ls-files --others --exclude-standard -- Sources Plugins 2>/dev/null | head -n 1)
fi
version="$package_version+$commit${changes:+-dirty}"

if [ -z "${2:-}" ]; then
  printf '%s\n' "$version"
  exit 0
fi
mkdir -p "$2"
file="$2/BuildVersion.swift"
source="// Generated by the StampVersion build plugin, from Scripts/build-version.sh. Do not edit.
enum BuildVersion { static let string = \"$version\" }"
[ "$(cat "$file" 2>/dev/null)" = "$source" ] || printf '%s\n' "$source" > "$file"
